#!/bin/sh
CLAUDUCTOR_FW=$(cd "$(dirname "$0")/../../.." && pwd) # clauductor plugin: the plugin root (framework/internal/plugin)
# render.sh: render the Ideas queue (the Ideas page's database) as IDEAS_FILE, and summarise it.
# Plain sh and jq; no Node.
#
# WHY. People add ideas on a claude.ai page (IDEAS_PAGE, registered in ARTIFACT_REGISTRY) from the
# phone, the desktop app or the web, and with `/ideas` in Claude Code. The page's database is the
# ONE place an idea is written. The repo needs the queue as planning context beside the roadmap, so
# session-close dumps the collection and this script regenerates IDEAS_FILE from it IN FULL. A copy
# regenerated whole cannot drift, only go stale, and two closes cannot fight over it: a conflict is
# resolved by re-running this.
#
# INPUT is a directory exactly as `ArtifactData` `list` with `out_dir` leaves it:
# `<dir>/ideas/<doc_id>.json`, one JSON document per idea. `<dir>` itself may be the `ideas` folder.
# No network and no clock: the same files give the same bytes.
#
#   render.sh <dir> [--names <file>] [--out <file>]
#       Render. `--names` is a JSON object {authorId: "display name"} the session writes from
#       `ArtifactData` `profiles`; an id with no name renders as "someone". Without --out, stdout.
#   render.sh <dir> --summary [--against <file>]
#       One line for session-start: counts by status, and how many ideas changed after the
#       rendered file's `data-through` stamp ("K ideas newer than docs/ideas.md").
#   render.sh --check <file>
#       Exit 0 only if the file is a renderer's output, unedited (checks/queue.sh runs it).
#   render.sh --url
#       The Ideas page's url, from the registry (IDEAS_PAGE in ARTIFACT_REGISTRY's "pages").
#   render.sh --mint
#       {"id": "cc-<random uuid>", "now": "<UTC ISO time>"}: a new idea's doc id and timestamp, for
#       `/ideas` (the reference minted them with node -e).
#
# THE HEADER CARRIES TWO STAMPS. `data-through` is the latest `updatedAt` in the data it was
# rendered from, which the summary compares against (a file's mtime would be a clock, and git
# checkouts reset it). It trusts the writers' clocks. `body-sha256` is the hash of everything after
# the header line, which --check recomputes: a hand edit to the body fails the gate.
#
# A document that is not an idea (not a JSON object, no string `text`, or a status that is not one
# of the four) is REFUSED, naming the file, rather than skipped: a skipped document is a smaller,
# plausible queue. Everything a viewer typed is data: escaped for Markdown, never interpreted.
#
# THE SAME OUTPUT AS Standing Tee's infra/ideas-render.mjs, byte for byte below the header line,
# so the body hash is the same; --check accepts either renderer's header. The module README lists
# where the two deliberately differ.
#
# Exit: 0 done; 2 refused (the reason on stderr, prefixed "ideas-render: ").
ROOT=$(case $CLAUDUCTOR_FW in (*/.claude) dirname "$CLAUDUCTOR_FW" ;; (*) [ -n "${ROOT:-}" ] && echo "$ROOT" || git rev-parse --show-toplevel 2>/dev/null || pwd ;; esac)
# shellcheck disable=SC1091
. "$CLAUDUCTOR_FW/lib/conf.sh"

die() { printf 'ideas-render: %s\n' "$*" >&2; exit 2; }
command -v jq >/dev/null 2>&1 || die "jq is not installed"

IFILE=${IDEAS_FILE:-docs/ideas.md}
REG=${ARTIFACT_REGISTRY:-docs/artifacts.json}
PAGE=${IDEAS_PAGE:-docs/ideas.html}
GENERATOR=".claude/modules/ideas/bin/render.sh"

# sha256 of stdin, hex.
sha256() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum | cut -c1-64
  elif command -v shasum >/dev/null 2>&1; then shasum -a 256 | cut -c1-64
  elif command -v openssl >/dev/null 2>&1; then openssl dgst -sha256 -r | cut -c1-64
  else die "no sha256 tool (sha256sum, shasum or openssl) is installed"; fi
}

# JavaScript's whitespace (String.prototype.trim and /\s/), spelt out: Oniguruma's \s also matches
# U+0085 and misses U+FEFF, and the output must be the reference's, byte for byte.
JQ_DEFS='
  def ws: "[\t\n\u000b\f\r \u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]";
  def jstrim: sub("\\A" + ws + "+"; "") | sub(ws + "+\\z"; "");
  def inline: gsub(ws + "+"; " ") | jstrim | gsub("(?<c>[\\\\`*_\\[\\]<>#|~])"; "\\\(.c)");
  def str: if type == "string" then . else "" end;
  # A time as the page and /ideas write it (toISOString), or a bare date; with an offset allowed.
  # The summary compares these as strings and the file prints their day, so anything else is refused.
  def iso: test("\\A[0-9]{4}-[0-9]{2}-[0-9]{2}(T[0-9]{2}:[0-9]{2}(:[0-9]{2}(\\.[0-9]+)?)?(Z|[+-][0-9]{2}:?[0-9]{2})?)?\\z");
'
# The page's status menu offers the same four ids, in this order.
STATUSES='[{"id":"not-touched","heading":"Not touched"},{"id":"discussed","heading":"Discussed"},{"id":"roadmap","heading":"On the roadmap"},{"id":"parked","heading":"Parked"}]'

# The header line: any renderer's name, then the two stamps. Standing Tee's names
# infra/ideas-render.mjs; this one names itself.
JQ_HEADER='
  capture("\\A<!-- generated by [^\n]+? — do not edit; add ideas on the Ideas page or with /ideas\\. data-through: (?<through>[^\t\n\u000b\f\r \u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]+) · body-sha256: (?<sha>[0-9a-f]{64}) -->\n")'

# header_of FILE: "<data-through> <body-sha256>" when FILE starts with a well-formed header line,
# else nothing.
header_of() {
  jq -Rsr "$JQ_HEADER | \"\\(.through) \\(.sha)\"" "$1" 2>/dev/null
}
# body_of FILE: everything after the first line, byte for byte.
body_of() { tail -n +2 "$1"; }

# why_not FILE: why FILE is not a renderer's untouched output, or nothing when it is.
why_not() {
  h=$(header_of "$1")
  [ -n "$h" ] || { echo "it does not begin with the generated header"; return; }
  [ "$(body_of "$1" | sha256)" = "${h#* }" ] || { echo "its body no longer matches the hash in its header: it was edited by hand"; return; }
  # The data-through stamp sits outside the hashed body (so the hash stays the reference's), so it
  # is held to the body instead: "none" only when every listed idea renders "undated" (updatedAt
  # falls back to createdAt), an ISO time otherwise.
  # Undated lines are counted, not dated ones: a note or text is free text and may hold ", <date>",
  # but every undated line the renderer writes ends ", undated" or has ", undated. Note: ", so its
  # own output always passes. The one false pass, a forged none over a dated idea whose note ends
  # ", undated" or whose text, name or note holds ", undated. Note: " (NULs removed), is loud: under
  # none, --summary counts every idea as newer.
  # Both counts strip NULs first: jq writes a JSON \u0000 as a raw NUL, and greps disagree on one
  # (GNU ends a line there, BSD ends a match there, and either prints "Binary file ... matches" in
  # place of a line), so one in an idea's text, row or author would split or cut the line it is on.
  t=${h%% *}; n=$(body_of "$1" | tr -d '\000' | grep -c '^- \*\*')
  if [ "$n" -eq 0 ]; then [ "$t" = none ] || echo "its header's data-through ($t) dates a body that lists no idea: it was edited by hand"
  elif [ "$t" = none ]; then
    undated=$(body_of "$1" | tr -d '\000' | grep -Ec '^- \*\*.*, undated($|\. Note: )')
    [ "$undated" -eq "$n" ] || echo "its header's data-through says none, but the body lists $((n - undated)) dated ideas: it was edited by hand"
  elif ! printf '%s' "$t" | grep -Eq '^[0-9]{4}-[0-9]{2}-[0-9]{2}(T[0-9]{2}:[0-9]{2}(:[0-9]{2}(\.[0-9]+)?)?(Z|[+-][0-9]{2}:?[0-9]{2})?)?$'; then
    echo "its header's data-through ($t) is not an ISO time: it was edited by hand"
  fi
}

# ── arguments: each flag once; a value never starts with -- ───────────────────────────────────
CHECK="" NAMES="" OUT="" AGAINST="" SUMMARY="" URL="" POS="" npos=0
need_val() {  # need_val FLAG [VALUE...]: VALUE exists and does not start with --
  [ $# -ge 2 ] || die "$1 needs a value"
  case $2 in --*) die "$1 needs a value" ;; esac
}
while [ $# -gt 0 ]; do
  case $1 in
    --check) [ -z "$CHECK" ] || die "--check given twice"; need_val "$@"; CHECK=$2; shift 2 ;;
    --names) [ -z "$NAMES" ] || die "--names given twice"; need_val "$@"; NAMES=$2; shift 2 ;;
    --out) [ -z "$OUT" ] || die "--out given twice"; need_val "$@"; OUT=$2; shift 2 ;;
    --against) [ -z "$AGAINST" ] || die "--against given twice"; need_val "$@"; AGAINST=$2; shift 2 ;;
    --summary) SUMMARY=1; shift ;;
    --url) URL=1; shift ;;
    --mint) MINT=1; shift ;;
    *) POS=$1; npos=$((npos + 1)); shift ;;
  esac
done

if [ -n "${MINT:-}" ]; then
  [ -z "$URL$CHECK$NAMES$OUT$AGAINST$SUMMARY" ] && [ "$npos" -eq 0 ] || die "--mint takes nothing else"
  # A version-4 UUID from 16 random bytes: the 13th hex digit is 4, the 17th one of 8, 9, a, b.
  hex=$(od -An -N16 -tx1 /dev/urandom | tr -d ' \n')
  [ ${#hex} -eq 32 ] || die "could not read 16 random bytes from /dev/urandom"
  v=$(printf '%s' "$hex" | cut -c17); case $v in [0-3]) y=8 ;; [4-7]) y=9 ;; [89ab]) y=a ;; *) y=b ;; esac
  uuid="$(printf '%s' "$hex" | cut -c1-8)-$(printf '%s' "$hex" | cut -c9-12)-4$(printf '%s' "$hex" | cut -c14-16)-$y$(printf '%s' "$hex" | cut -c18-20)-$(printf '%s' "$hex" | cut -c21-32)"
  jq -cn --arg id "cc-$uuid" --arg now "$(date -u +%Y-%m-%dT%H:%M:%S.000Z)" '{id: $id, now: $now}'
  exit 0
fi

if [ -n "$URL" ]; then
  [ -z "$CHECK$NAMES$OUT$AGAINST$SUMMARY" ] && [ "$npos" -eq 0 ] || die "--url takes nothing else"
  [ -f "$ROOT/$REG" ] || die "$REG does not exist, so the Ideas page has no url (the artifacts module's README)"
  u=$(jq -r --arg p "$PAGE" '.pages[$p].url // empty | strings' "$ROOT/$REG" 2>/dev/null)
  [ -n "$u" ] || die "$REG registers no url for $PAGE: the queue cannot be reached (the ideas module's README: publish the page, then register it)"
  printf '%s\n' "$u"; exit 0
fi

if [ -n "$CHECK" ]; then
  [ -z "$NAMES$OUT$AGAINST$SUMMARY" ] && [ "$npos" -eq 0 ] || die "--check takes one file and nothing else"
  [ -f "$CHECK" ] || die "$CHECK: no such file"
  why=$(why_not "$CHECK")
  [ -z "$why" ] || die "$CHECK: $why. Regenerate it; never edit it."
  printf '%s: generated, unedited\n' "$CHECK"; exit 0
fi

{ [ "$npos" -eq 1 ] && [ "${POS#--}" = "$POS" ]; } || die "usage: render.sh <dump-dir> [--names f] [--out f] | --summary [--against f] | --check f | --url"

# ── the dump ─────────────────────────────────────────────────────────────────────────────────
dir=$POS
while [ "${dir%/}" != "$dir" ] && [ "$dir" != / ]; do dir=${dir%/}; done
# An EMPTY collection makes ArtifactData `list` write nothing, not even the directory. So a missing
# directory is ambiguous (an empty queue, or a list that never ran): refuse rather than guess,
# because rendering "empty" from a skipped read would wipe the file. The session's steps
# `mkdir -p` the directory after a SUCCESSFUL list.
[ -e "$dir" ] || die "$dir: no dump directory. An empty collection writes nothing, so after a SUCCESSFUL ArtifactData list run \`mkdir -p $dir/ideas\`; if the list failed, do not render."
d=$dir; [ -d "$dir/ideas" ] && d="$dir/ideas"
[ -d "$d" ] || die "$d: not a directory"

W=$(mktemp -d "${TMPDIR:-/tmp}/ideas-render.XXXXXX") || die "mktemp failed"
trap 'rm -rf "$W"' EXIT
: > "$W/ideas"
BOM=$(printf '\357\273\277')
# One document per file; the doc id is the file name (ArtifactData writes the BARE body).
ls -A "$d" | LC_ALL=C sort | grep '\.json$' > "$W/files"
while IFS= read -r f; do
  p="$d/$f"; id=${f%.json}
  if [ "$(head -c 3 "$p")" = "$BOM" ]; then die "$p: not JSON (a byte-order mark before the document)"; fi
  if ! jq -s . "$p" > "$W/doc" 2> "$W/err"; then
    die "$p: not JSON ($(sed -n '1{s/^jq: parse error: //;s/^jq: error[^:]*: //;p;}' "$W/err"))"
  fi
  r=$(jq -c --arg id "$id" "$JQ_DEFS"'
    if length != 1 then {err: "not JSON (\(length) JSON values, not one)"}
    else .[0] as $d
    | if ($d | type) != "object" then {err: "not a JSON object"}
      elif ($d.text | type) != "string" or ($d.text | jstrim) == "" then {err: "has no text — not an idea document"}
      elif ($d.status | type) != "string" or ($d.status | IN("not-touched", "discussed", "roadmap", "parked") | not)
        then {err: "unknown status \(if $d | has("status") then $d.status | tojson else "undefined" end) (want one of not-touched, discussed, roadmap, parked)"}
      elif ($d.createdAt | str) as $t | $t != "" and ($t | iso | not) then {err: "createdAt is not an ISO time: \($d.createdAt | tojson)"}
      elif ($d.updatedAt | str) as $t | $t != "" and ($t | iso | not) then {err: "updatedAt is not an ISO time: \($d.updatedAt | tojson)"}
      else {ok: {id: $id, text: $d.text, note: ($d.note | str), authorId: ($d.authorId | str),
                 createdAt: ($d.createdAt | str),
                 updatedAt: (($d.updatedAt | str) as $u | if $u == "" then ($d.createdAt | str) else $u end),
                 status: $d.status, roadmapRow: ($d.roadmapRow | str)}}
      end
    end' "$W/doc") || die "$p: could not be read"
  e=$(printf '%s' "$r" | jq -r '.err // empty')
  [ -z "$e" ] || die "$p: $e"
  printf '%s' "$r" | jq -c '.ok' >> "$W/ideas"
done < "$W/files"
# Oldest first by createdAt, then by id: a total, stable order, whatever the listing order.
jq -s 'sort_by(.createdAt, .id)' "$W/ideas" > "$W/all" || die "could not order the ideas"
# Checked after the read, as the reference does: a bad document is named first.
if [ -n "$SUMMARY" ]; then [ -z "$NAMES$OUT" ] || die "--summary takes only --against"
else [ -z "$AGAINST" ] || die "--against goes with --summary"; fi

if [ -n "$SUMMARY" ]; then
  rendered="" through=""
  if [ -n "$AGAINST" ]; then
    [ -f "$AGAINST" ] || die "$AGAINST: no such file"
    h=$(header_of "$AGAINST"); rendered=1; through=${h%% *}
  fi
  jq -r --arg file "$IFILE" --arg rendered "$rendered" --arg through "$through" '
    def count($s): map(select(.status == $s)) | length;
    "Ideas: \(count("not-touched")) not touched, \(count("discussed")) discussed, \(count("parked")) parked, \(count("roadmap")) on the roadmap"
    + if $rendered == "" then ""
      elif $through == "" then ". \($file) has no generated header: CANNOT CHECK how stale it is"
      else (map(select($through == "none" or .updatedAt > $through)) | length) as $n
        | if $n > 0 then ". \($n) idea\(if $n == 1 then "" else "s" end) newer than \($file)" else ". \($file) is current" end
      end' "$W/all"
  exit 0
fi

# ── render ───────────────────────────────────────────────────────────────────────────────────
if [ -n "$NAMES" ]; then
  [ -f "$NAMES" ] || die "$NAMES: no such file"
  jq -e 'type == "object"' "$NAMES" >/dev/null 2>&1 || die "$NAMES: want a JSON object {authorId: name}"
  cp "$NAMES" "$W/names"
else echo '{}' > "$W/names"; fi
# Who scopes the queue: the owner by name when project.conf names them, else by role.
if [ -n "${OWNER_NAME:-}" ]; then owner=$OWNER_NAME
else role=${OWNER_ROLE:-owner}; owner="The $role"; fi

jq -j --slurpfile names "$W/names" --argjson statuses "$STATUSES" --arg reg "$REG" --arg owner "$owner" "$JQ_DEFS"'
  ($names[0]) as $nm
  | def who($id): (if $id != "" and (($nm[$id]? // null) | type) == "string" then $nm[$id] | jstrim else "" end)
      | if . != "" then inline else "someone" end;
  reverse as $newest
  | ["# Ideas", "",
     "The live queue is the Ideas page (its link is in `\($reg)`). Session close",
     "regenerates this file from it; `/ideas` adds one from Claude Code. \($owner) scopes which ideas",
     "become roadmap rows.", ""]
    + ([$statuses[] as $s
        | ($newest | map(select(.status == $s.id))) as $g
        | ["## \($s.heading) (\($g | length))", ""]
          + (if ($g | length) == 0 then ["None.", ""]
             else [$g[] | "- **\(.text | inline)**"
                     + (if $s.id == "roadmap" and .roadmapRow != "" then " → roadmap row \(.roadmapRow | inline)" else "" end)
                     + " — \(who(.authorId)), \(.createdAt | .[0:10] | if . == "" then "undated" else . end)"
                     + (if .note != "" then ". Note: \(.note | inline)" else "" end)] + [""]
             end)] | add)
  | join("\n")' "$W/all" > "$W/body" || die "could not render the queue"
through=$(jq -r 'map(.updatedAt) | reduce .[] as $u (""; if $u > . then $u else . end) | if . == "" then "none" else . end' "$W/all")
sha=$(sha256 < "$W/body")
{ printf '<!-- generated by %s — do not edit; add ideas on the Ideas page or with /ideas. data-through: %s · body-sha256: %s -->\n' "$GENERATOR" "$through" "$sha"
  cat "$W/body"; } > "$W/out"
if [ -n "$OUT" ]; then cat "$W/out" > "$OUT" || die "$OUT: could not be written"
else cat "$W/out"; fi
